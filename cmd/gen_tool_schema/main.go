// Command gen_tool_schema writes the structural half of the tool surface to
// site/src/data/tool-schema.json, for the documentation site to render.
//
// The site's reference tables state, for every parameter and every returned
// field, its name, its type and whether it is required. All three are facts the
// server already knows: they come out of the registered JSON Schema. Restating
// them by hand across two locales is 89 rows nobody can check, and it had
// already drifted — download's `resolved` field is in the schema and absent from
// the table that is supposed to list every field it returns.
//
// What this command deliberately does NOT emit is the descriptions. The
// jsonschema tags are written for a model — "array of collections to search:
// nonfiction fiction articles magazines comics standards fiction_rus (omit for
// all). Use fiction for novels comics for graphic novels" — and the site's
// tables are written for a reader: "Collections to search: `nonfiction`,
// `fiction`, … Omit for all collections." Both are correct for their audience,
// and generating one from the other would replace the prose a person needs with
// the prose a model needs. Structure is generated; prose stays authored, and the
// ParamTable component fails the build if a page describes a parameter the
// schema does not have, or omits one it does.
//
// Usage:
//
//	go run ./cmd/gen_tool_schema/           # rewrite the file
//	go run ./cmd/gen_tool_schema/ --check   # fail if it is stale (CI)
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"slices"
	"sort"
	"strings"

	"github.com/modelcontextprotocol/go-sdk/mcp"

	"github.com/jmrplens/libgen-mcp/cmd/internal/mcpsurface"
	"github.com/jmrplens/libgen-mcp/internal/tools"
)

// relPath is where the generated file lives, relative to the repository root.
const relPath = "site/src/data/tool-schema.json"

// field is one parameter or one returned field, reduced to what a table row
// states about it.
type field struct {
	Name     string   `json:"name"`
	Type     string   `json:"type"`
	Required bool     `json:"required"`
	Enum     []string `json:"enum,omitempty"`
}

// toolSchema is one tool's two schemas, each as an ordered list of fields.
type toolSchema struct {
	Input  []field `json:"input"`
	Output []field `json:"output"`
}

// promptSchema is one prompt's arguments.
type promptSchema struct {
	Arguments []field `json:"arguments"`
}

// document is the generated file's shape.
type document struct {
	// Note is emitted into the artifact itself: whoever opens it next should
	// not have to find this command to learn that it is generated.
	Note    string                  `json:"_note"`
	Tools   map[string]toolSchema   `json:"tools"`
	Prompts map[string]promptSchema `json:"prompts"`
}

const note = "Generated by cmd/gen_tool_schema from the registered MCP surface. " +
	"Do not edit by hand; run `make gen-tool-schema`. Descriptions are not " +
	"generated: they are authored per locale in the documentation pages."

// schemaTypes reads a schema's declared type, which JSON Schema allows to be
// either a single string or a list of them, and drops "null" — an optional Go
// pointer is expressed as `["object", "null"]`, and the tables name the type it
// carries when it is present.
func schemaTypes(raw any) []string {
	switch v := raw.(type) {
	case string:
		if v == "" || v == "null" {
			return nil
		}
		return []string{v}
	case []any:
		out := make([]string, 0, len(v))
		for _, item := range v {
			if s, ok := item.(string); ok && s != "" && s != "null" {
				out = append(out, s)
			}
		}
		return out
	default:
		return nil
	}
}

// typeName renders a schema's type the way the reference tables name it, so a
// generated row and the prose beside it agree on vocabulary: `string[]` rather
// than "array of strings", because that is what the tables already said.
//
// The schema arrives as a decoded map rather than a typed value: it comes from
// a real tools/list round-trip, which is what makes the artifact describe what
// the server actually advertises rather than what the structs suggest.
func typeName(prop map[string]any) string {
	types := schemaTypes(prop["type"])
	if len(types) == 0 {
		if _, ok := prop["items"]; ok {
			return "array"
		}
		if _, ok := prop["properties"]; ok {
			return "object"
		}
		return "any"
	}
	if slices.Contains(types, "array") {
		items, _ := prop["items"].(map[string]any)
		inner := typeName(items)
		if inner == "" || inner == "any" {
			return "array"
		}
		return inner + "[]"
	}
	if len(types) == 1 {
		return types[0]
	}
	return strings.Join(types, " or ")
}

// enumValues renders an enum as sorted strings, looking inside `items` for an
// array whose members are constrained rather than the array itself.
func enumValues(prop map[string]any) []string {
	enum, ok := prop["enum"].([]any)
	if !ok || len(enum) == 0 {
		items, isMap := prop["items"].(map[string]any)
		if !isMap {
			return nil
		}
		enum, ok = items["enum"].([]any)
		if !ok || len(enum) == 0 {
			return nil
		}
	}
	// NOT sorted. The download tool's `source` enum is pinned from the enabled
	// chain in chain order, and that order is the thing it is telling the caller;
	// alphabetising it here would publish `annas` first and `unpaywall` twelfth.
	out := make([]string, 0, len(enum))
	for _, v := range enum {
		out = append(out, fmt.Sprint(v))
	}
	return out
}

// requiredSet reads a schema's `required` array into a lookup.
func requiredSet(schema map[string]any) map[string]bool {
	required := map[string]bool{}
	list, ok := schema["required"].([]any)
	if !ok {
		return required
	}
	for _, name := range list {
		if s, isStr := name.(string); isStr {
			required[s] = true
		}
	}
	return required
}

// declaredOrder is the order each tool's schemas name their fields.
//
// It cannot come from the round-trip. A tools/list response carries `properties`
// as a JSON object, and the SDK decodes it into map[string]any before this
// command sees it, so the order is gone by then — re-encoding a map only
// re-sorts it alphabetically.
//
// The order matters, and is not incidental: it is the order the reference
// tables already use, because both come from the same struct — `query` before
// `topics` before `search_in`, the parameters a caller reaches for first ahead
// of the ones they rarely set. Sorting alphabetically instead would open every
// search table with `extra_sources`, which is a lookup table's order imposed on
// a page people read top to bottom.
//
// So the ORDER is read from the structs, while the field set, the types and the
// required flags all still come from the round-trip. If the two ever disagree,
// fieldsOf reports it rather than quietly preferring one.
var declaredOrder = map[string][2]reflect.Type{
	"search":      {reflect.TypeOf(tools.SearchInput{}), reflect.TypeOf(tools.SearchOutput{})},
	"get_details": {reflect.TypeOf(tools.DetailsInput{}), reflect.TypeOf(tools.DetailsOutput{})},
	"download":    {reflect.TypeOf(tools.DownloadInput{}), reflect.TypeOf(tools.DownloadOutput{})},
	"read":        {reflect.TypeOf(tools.ReadInput{}), reflect.TypeOf(tools.ReadOutput{})},
}

// jsonNames lists a struct's JSON field names in declaration order, skipping
// fields the encoder omits and flattening embedded structs where it does.
//
// The flattening is not a nicety: DownloadOutput declares two fields of its own
// and embeds libgen.DownloadResult, whose seven fields the encoder promotes
// alongside them. Reading only the outer struct would report those seven as
// advertised-but-undeclared and fail the run.
func jsonNames(t reflect.Type) []string {
	names := make([]string, 0, t.NumField())
	for i := range t.NumField() {
		f := t.Field(i)
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, _, _ := strings.Cut(tag, ",")

		// An anonymous struct with no name of its own has its fields promoted
		// into the enclosing object, at this position.
		if f.Anonymous && name == "" {
			embedded := f.Type
			for embedded.Kind() == reflect.Pointer {
				embedded = embedded.Elem()
			}
			if embedded.Kind() == reflect.Struct {
				names = append(names, jsonNames(embedded)...)
				continue
			}
		}
		if name != "" {
			names = append(names, name)
		}
	}
	return names
}

// fieldsOf flattens a schema's properties into rows, in declaration order.
//
// `order` is the struct's field list; the schema is the authority on which
// fields exist and what they are. A field in one and not the other is a
// mismatch between the registered surface and the type it was inferred from,
// which is a bug in the server rather than something to paper over here.
func fieldsOf(tool, section string, raw any, order []string) ([]field, error) {
	schema, ok := raw.(map[string]any)
	if !ok {
		return nil, nil
	}
	props, ok := schema["properties"].(map[string]any)
	if !ok {
		return nil, nil
	}
	required := requiredSet(schema)

	seen := make(map[string]bool, len(order))
	out := make([]field, 0, len(props))
	for _, name := range order {
		prop, isMap := props[name].(map[string]any)
		if !isMap {
			return nil, fmt.Errorf(
				"%s %s: the struct declares %q but the registered schema does not",
				tool, section, name)
		}
		seen[name] = true
		out = append(out, field{
			Name:     name,
			Type:     typeName(prop),
			Required: required[name],
			Enum:     enumValues(prop),
		})
	}

	missing := make([]string, 0)
	for name := range props {
		if !seen[name] {
			missing = append(missing, name)
		}
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return nil, fmt.Errorf(
			"%s %s: the registered schema advertises %v, which the struct's field order does not cover",
			tool, section, missing)
	}
	return out, nil
}

// build reads the registered surface and reduces it to the generated document.
func build() (*document, error) {
	cfg := mcpsurface.DocsConfig()
	tools, err := mcpsurface.Tools(cfg)
	if err != nil {
		return nil, fmt.Errorf("read tools: %w", err)
	}
	prompts, err := mcpsurface.Prompts(cfg)
	if err != nil {
		return nil, fmt.Errorf("read prompts: %w", err)
	}

	doc := &document{
		Note:    note,
		Tools:   make(map[string]toolSchema, len(tools)),
		Prompts: make(map[string]promptSchema, len(prompts)),
	}
	for _, tool := range tools {
		types, known := declaredOrder[tool.Name]
		if !known {
			return nil, fmt.Errorf("tool %q has no entry in declaredOrder", tool.Name)
		}
		in, err := fieldsOf(tool.Name, "input", tool.InputSchema, jsonNames(types[0]))
		if err != nil {
			return nil, err
		}
		out, err := fieldsOf(tool.Name, "output", tool.OutputSchema, jsonNames(types[1]))
		if err != nil {
			return nil, err
		}
		doc.Tools[tool.Name] = toolSchema{Input: in, Output: out}
	}
	for _, prompt := range prompts {
		doc.Prompts[prompt.Name] = promptSchema{Arguments: promptArguments(prompt)}
	}
	return doc, nil
}

// promptArguments reduces a prompt's declared arguments to rows, in the order
// the prompt declares them — the same reason propertyOrder exists. A prompt has
// no JSON Schema, only a flat argument list, so this does not go through
// fieldsOf.
func promptArguments(prompt *mcp.Prompt) []field {
	args := make([]field, 0, len(prompt.Arguments))
	for _, arg := range prompt.Arguments {
		args = append(args, field{Name: arg.Name, Type: "string", Required: arg.Required})
	}
	return args
}

// render encodes the document the way the file is committed: two-space indent
// and a trailing newline, so `--check` compares like with like.
func render(doc *document) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func main() {
	check := flag.Bool("check", false, "fail if the committed file is stale instead of rewriting it")
	flag.Parse()

	if err := run(*check); err != nil {
		fmt.Fprintf(os.Stderr, "gen_tool_schema: %v\n", err)
		os.Exit(1)
	}
}

// run generates the document and either writes it or compares it.
func run(check bool) error {
	root, err := mcpsurface.ProjectRoot()
	if err != nil {
		return err
	}
	doc, err := build()
	if err != nil {
		return err
	}
	want, err := render(doc)
	if err != nil {
		return err
	}
	path := filepath.Join(root, relPath)

	if !check {
		if err := os.WriteFile(path, want, 0o644); err != nil {
			return err
		}
		fmt.Printf("wrote %s (%d tools, %d prompts)\n", relPath, len(doc.Tools), len(doc.Prompts))
		return nil
	}

	got, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("%s: %w (run `make gen-tool-schema`)", relPath, err)
	}
	if !bytes.Equal(got, want) {
		return fmt.Errorf("%s is stale — run `make gen-tool-schema`", relPath)
	}
	fmt.Printf("%s is up to date\n", relPath)
	return nil
}
