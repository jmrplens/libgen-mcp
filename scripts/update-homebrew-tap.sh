#!/usr/bin/env bash
# Regenerate the Homebrew tap formula (jmrplens/homebrew-tap) for a release.
#
# Renders Formula/libgen-mcp.rb from the release version and the per-platform
# SHA256 hashes in GoReleaser's checksums.txt, then commits and pushes it to the
# tap repository. The caller must have push access to the tap (in CI: an SSH
# deploy key wired through GIT_SSH_COMMAND).
#
# Usage: update-homebrew-tap.sh <checksums-file> <version> [tap-clone-dir] [--dry-run]
#
# --dry-run does everything but the push: the formula is rendered, checked with
# `ruby -c` and committed to the local clone, and the commit is printed instead
# of pushed. It is what a release rehearsal runs, so the whole path up to the one
# irreversible step is exercised with real checksums.
#
# The hashes come from checksums.txt rather than from a download of the assets,
# which is what makes the formula's `sha256` lines as trustworthy as the
# cosign-signed manifest the release publishes.

set -euo pipefail

DRY_RUN=0
ARGS=()
for arg in "$@"; do
	case "$arg" in
	--dry-run) DRY_RUN=1 ;;
	*) ARGS+=("$arg") ;;
	esac
done
set -- "${ARGS[@]}"

CHECKSUMS_FILE="${1:?Usage: $0 <checksums-file> <version> [tap-clone-dir] [--dry-run]}"
VERSION="${2:?Usage: $0 <checksums-file> <version> [tap-clone-dir] [--dry-run]}"
TAP_DIR="${3:-homebrew-tap}"
TAP_REPO="${TAP_REPO:-git@github.com:jmrplens/homebrew-tap.git}"
BASE_URL="https://github.com/jmrplens/libgen-mcp/releases/download/v${VERSION}"

sha_for() {
	local name="$1" sha
	sha=$(awk -v n="$name" '$2 == n {print $1}' "$CHECKSUMS_FILE")
	if [[ -z "$sha" ]]; then
		echo "ERROR: no checksum for $name in $CHECKSUMS_FILE" >&2
		exit 1
	fi
	echo "$sha"
}

SHA_DARWIN_ARM=$(sha_for libgen-mcp-darwin-arm64)
SHA_DARWIN_INTEL=$(sha_for libgen-mcp-darwin-amd64)
SHA_LINUX_ARM=$(sha_for libgen-mcp-linux-arm64)
SHA_LINUX_INTEL=$(sha_for libgen-mcp-linux-amd64)

if [[ ! -d "$TAP_DIR/.git" ]]; then
	git clone --depth 1 "$TAP_REPO" "$TAP_DIR"
fi

mkdir -p "$TAP_DIR/Formula"
cat >"$TAP_DIR/Formula/libgen-mcp.rb" <<EOF
# typed: false
# frozen_string_literal: true

# This file is generated by the release workflow of
# https://github.com/jmrplens/libgen-mcp — do not edit by hand.
class LibgenMcp < Formula
  desc "MCP server for books and papers: Library Genesis and open-access search, download and reading"
  homepage "https://jmrp.io/docs/libgen-mcp"
  version "${VERSION}"
  license "MIT"

  livecheck do
    url "https://github.com/jmrplens/libgen-mcp"
    strategy :github_latest
  end

  on_macos do
    on_arm do
      url "${BASE_URL}/libgen-mcp-darwin-arm64"
      sha256 "${SHA_DARWIN_ARM}"
    end
    on_intel do
      url "${BASE_URL}/libgen-mcp-darwin-amd64"
      sha256 "${SHA_DARWIN_INTEL}"
    end
  end

  on_linux do
    on_arm do
      url "${BASE_URL}/libgen-mcp-linux-arm64"
      sha256 "${SHA_LINUX_ARM}"
    end
    on_intel do
      url "${BASE_URL}/libgen-mcp-linux-amd64"
      sha256 "${SHA_LINUX_INTEL}"
    end
  end

  def install
    bin.install Dir["libgen-mcp-*"].first => "libgen-mcp"
  end

  def caveats
    <<~EOS
      Homebrew manages upgrades for this binary.

      It needs no account, API key or token. Configure your MCP client with:
        command: #{HOMEBREW_PREFIX}/bin/libgen-mcp

      Per-client JSON and every setting:
        https://jmrp.io/docs/libgen-mcp/getting-started/
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/libgen-mcp --version")
  end
end
EOF

cd "$TAP_DIR"
ruby -c Formula/libgen-mcp.rb >/dev/null

# The bot identity, as the release workflow's own commit back to main uses: this
# is a machine-made commit in another repository, pushed by a deploy key.
git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
git add Formula/libgen-mcp.rb

if git diff --cached --quiet; then
	echo "Tap formula already up to date for v${VERSION}"
	exit 0
fi

git commit -m "libgen-mcp ${VERSION}"
if [[ "$DRY_RUN" -eq 1 ]]; then
	echo "Dry run: the tap would receive this commit, nothing was pushed"
	git --no-pager show --stat --format='%h %s' HEAD
	git --no-pager diff HEAD~1 -- Formula/libgen-mcp.rb
	exit 0
fi
git push origin HEAD:main
echo "Tap formula updated to v${VERSION}"
